"""Build docs/index.html from output/result.json for GitHub Pages."""
from __future__ import annotations

import html
import json
from pathlib import Path

from .config import Config


def _escape(value: object) -> str:
    return html.escape("" if value is None else str(value), quote=True)


def render_html(result: dict) -> str:
    questions = result.get("questions") or []
    blocks = []
    for row in questions:
        ans = row.get("answer") or {}
        citations = ", ".join(ans.get("citations") or []) or "—"
        abstained = "yes" if ans.get("abstained") else "no"
        blocks.append(
            f"""
<section>
  <h2>{_escape(row.get('id'))}</h2>
  <p><strong>Question.</strong> {_escape(row.get('question'))}</p>
  <p><strong>Answer.</strong> {_escape(ans.get('text'))}</p>
  <p><strong>Citations.</strong> {_escape(citations)}</p>
  <p><strong>Abstained.</strong> {_escape(abstained)} · <strong>Mode.</strong> {_escape(ans.get('mode'))}</p>
</section>
"""
        )
    body = "\n".join(blocks) or "<p>No questions in the output.</p>"
    return f"""<!DOCTYPE html>
<html lang="en">
<head>
  <meta charset="utf-8">
  <meta name="viewport" content="width=device-width, initial-scale=1">
  <title>Exercise output — ai-getting-started-exercise</title>
  <style>
    body {{ font-family: system-ui, sans-serif; line-height: 1.5; max-width: 48rem;
           margin: 2rem auto; padding: 0 1rem; color: #111; }}
    h1, h2 {{ font-weight: 600; }}
    .meta {{ color: #444; }}
    pre {{ white-space: pre-wrap; background: #f5f5f5; padding: 1rem; overflow: auto; }}
  </style>
</head>
<body>
  <h1>Exercise output</h1>
  <p class="meta">
    Input: {_escape(result.get('input'))}.
    LLM: {_escape(result.get('llm'))}.
    Embeddings: {_escape(result.get('embeddings'))}.
    Generated (UTC): {_escape(result.get('generated_at'))}.
  </p>
  <p>Checked against the criterion written before running, in <code>CRITERIA.md</code>
     and <code>criteria.yaml</code>. This page is generated by
     <code>python -m exercise publish</code> and can be deployed to GitHub Pages
     via <code>.github/workflows/pages.yml</code> (manual dispatch).</p>
  {body}
  <h2>Extracted PDF text</h2>
  <pre>{_escape(result.get('extracted_text'))}</pre>
</body>
</html>
"""


def publish(cfg: Config | None = None) -> Path:
    cfg = cfg or Config.from_env()
    source = cfg.output_dir / "result.json"
    if not source.is_file():
        raise FileNotFoundError(
            f"Missing {source}. Run first: python -m exercise run"
        )
    result = json.loads(source.read_text(encoding="utf-8"))
    cfg.pages_dir.mkdir(parents=True, exist_ok=True)
    index = cfg.pages_dir / "index.html"
    index.write_text(render_html(result), encoding="utf-8")
    return index